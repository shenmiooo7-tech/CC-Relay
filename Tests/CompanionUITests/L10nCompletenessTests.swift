import XCTest
@testable import CompanionUI

final class L10nCompletenessTests: XCTestCase {
    func testResolvePrefersTheFirstLanguageTag() {
        XCTAssertEqual(L10nLanguage.resolve(preferredLanguages: ["zh-Hans"]), .zhHans)
        XCTAssertEqual(L10nLanguage.resolve(preferredLanguages: ["zh-Hant-TW"]), .zhHans)
        XCTAssertEqual(L10nLanguage.resolve(preferredLanguages: ["zh"]), .zhHans)
        XCTAssertEqual(L10nLanguage.resolve(preferredLanguages: ["zh_CN"]), .zhHans)
        XCTAssertEqual(L10nLanguage.resolve(preferredLanguages: ["ZH-Hans"]), .zhHans)
        XCTAssertEqual(L10nLanguage.resolve(preferredLanguages: ["en-US"]), .en)
        XCTAssertEqual(L10nLanguage.resolve(preferredLanguages: ["fr-FR"]), .en)
        XCTAssertEqual(L10nLanguage.resolve(preferredLanguages: ["en", "zh-CN"]), .en)
        XCTAssertEqual(L10nLanguage.resolve(preferredLanguages: []), .en)
        XCTAssertEqual(L10nLanguage.resolve(preferredLanguages: ["", "zh-Hans"]), .zhHans)
    }

    func testEveryKeyHasBothLanguagesAndMatchingParameters() {
        for key in L10nKey.allCases {
            let zh = key.template(.zhHans)
            let en = key.template(.en)
            XCTAssertFalse(zh.isEmpty, "\(key.rawValue) missing Chinese")
            XCTAssertFalse(en.isEmpty, "\(key.rawValue) missing English")
            XCTAssertEqual(
                L10nSubstituting.parameterNames(in: zh).sorted(),
                L10nSubstituting.parameterNames(in: en).sorted(),
                "\(key.rawValue) parameter names differ"
            )
            XCTAssertEqual(zh, expectedChinese[key], "\(key.rawValue) Chinese drifted")
        }
        XCTAssertEqual(Set(expectedChinese.keys), Set(L10nKey.allCases))
    }

    func testSubstitutionReplacesByNameAndDoesNotRescan() {
        let line = L10nKey.resetLine.string(in: .zhHans, parameters: [
            "countdown": "{h}",
            "time": "21:00",
        ])
        XCTAssertEqual(line, "21:00 · {h}")
        let failed = L10nKey.switchFailed.string(in: .en, parameters: ["reason": "Couldn't quit Claude"])
        XCTAssertEqual(failed, "Switch failed: Couldn't quit Claude")
    }

